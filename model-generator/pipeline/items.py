r"""Loose items (stacks on the floor, trays, goods...) are drawn by the game only as small 2D sprites, hidden in 3D. The DLL recognises
those sprites by where they sit in the objects sprite bank and draws a simple 3D item there instead.
usage: python -I items.py DATA OUT   ->  OUT/items.h (-> dll\src\items.h): sprite cell rectangles (objects.spritebank, 32 px cells) and a kind"""
import sys, os, re
DATA, OUT = sys.argv[1], sys.argv[2]
t = open(os.path.join(DATA, 'objects.spritebank'), encoding='latin1').read()
# kind: 1 ingredients crate, 2 cooked food (pot), 3 food trays, 4 shop goods box, 5 cloth pile, 6 mail / paper, 7 books, 8 logs / wood,
#       9 metal sheets / plates, 10 bricks / blocks
RULES = [(r'^(Stack)?Ingredients?\d*$', 1), (r'IngredientsCooked|^Stack.*Cooked', 2), (r'^(Stack)?FoodTray', 3), (r'^StackFoodTrays', 3),
         (r'ShopGoods', 4), (r'(Prisoner|Dirty|Crumpled).*Uniform|Laundry|Clothing|Sheets', 5), (r'^(Stack)?Mail', 6), (r'LibraryBook|Books?$', 7),
         (r'^(Stack)?(Log|Wood|Timber)', 8), (r'(Sheet)?Metal|LicensePlate|Plates?$', 9), (r'^(Stack)?(Brick|Concrete|Stone)', 10)]
rows = []
for m in re.finditer(r'\[i (\d+)\]"\s+Name (\S+)\s+x (\d+)\s+y (\d+)\s+w (\d+)\s+h (\d+)', t):
    idx, name = int(m.group(1)), m.group(2); x, y, w, h = map(int, m.groups()[2:])
    if not (name.startswith('Stack') or re.search(r'Ingredient|FoodTray|ShopGoods|Mail|LibraryBook|LicensePlate|Uniform', name)): continue
    if re.search(r'Shelf|Toolbar|Box$|Satchel|Top\d*$', name): continue      # furniture with its own 3D model, and toolbar icons
    kind = next((k for pat, k in RULES if re.search(pat, name)), 0)
    if kind: rows.append((x, y, w, h, kind, name))
with open(os.path.join(OUT, 'items.h'), 'w') as f:
    f.write('// generated by model-generator/pipeline/items.py: loose-item sprites in the objects sprite bank (cells of 32 px in the 4096 px bank)\n')
    f.write('struct ItemSprite { short x, y, w, h; unsigned char kind; };\n')
    f.write('static const ItemSprite kItemSprites[] = {\n' + ''.join('    {%d, %d, %d, %d, %d},      // %s\n' % (x, y, w, h, k, n) for x, y, w, h, k, n in rows) + '};\n')
print('item sprites:', len(rows)); print(', '.join('%s=%d' % (n, k) for x, y, w, h, k, n in rows[:40]))
